"""DEV-104 — when the cockpit writes a release note, it also rebuilds what the project derives from its notes.

13.10.2026 the cockpit corrected NEX Inbox 1.5.2's note (DEV-97) and committed ``RELEASE_NOTES.md`` alone. NEX Inbox
renders its notes from ``frontend/src/lib/release-notes.ts``, generated by ``npm run generate-release-notes`` and
guarded by its CI's "RELEASE_NOTES generated-file check" — the CI went red and the 1.8.0 build got a verification
round for it.
The same happens on every note the cockpit commits at a passed verification.

The project says what it derives: the ``generate-release-notes`` script in its ``frontend/package.json``. Without the
script nothing is derived and nothing runs. When the generator fails, the note is not committed half-way — the manager
is told why.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

from backend.services import orchestrator, release_note_writer
from tests.test_orchestrator_v2_verifikacia import _make_version, _msgs

DERIVED = "frontend/src/lib/release-notes.ts"


def _git(root: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True, text=True).stdout


@pytest.fixture
def project(tmp_path: Path) -> Path:
    root = tmp_path / "nex-inbox"
    (root / "frontend" / "src" / "lib").mkdir(parents=True)
    (root / "frontend" / "package.json").write_text(
        json.dumps({"scripts": {"generate-release-notes": "tsx scripts/generate-release-notes.ts"}}), encoding="utf-8"
    )
    (root / DERIVED).write_text("export const NOTES = [];\n", encoding="utf-8")
    _git(root.parent, "init", "-q", "-b", "main", str(root))
    _git(root, "config", "user.email", "studio@isnex.eu")
    _git(root, "config", "user.name", "NEX Studio")
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", "start")
    return root


@pytest.fixture
def writes_the_note(monkeypatch):
    def _write(db, version_id, root):
        note = Path(root) / "docs" / "specs" / "versions" / "v1.5.2" / "RELEASE_NOTES.md"
        note.parent.mkdir(parents=True, exist_ok=True)
        note.write_text("## v1.5.2\n\n- Faktúry od Kinekusu sa spracujú aj s čiarovými kódmi.\n", encoding="utf-8")
        return note

    monkeypatch.setattr(release_note_writer, "write_release_note", _write)
    monkeypatch.setattr(orchestrator, "_apply_customer_note_to_fix_epic", lambda db, vid: False)


def _generator(monkeypatch, *, fails: bool = False) -> list[Path]:
    """Stand-in for the project's generator: it rewrites the derived file from the notes, or fails."""
    ran: list[Path] = []

    def _run(frontend: Path):
        ran.append(frontend)
        if fails:
            return subprocess.CompletedProcess(["npm"], 1, "", "Error: Cannot find module 'tsx'\n")
        (frontend / "src" / "lib" / "release-notes.ts").write_text(
            'export const NOTES = ["Faktúry od Kinekusu sa spracujú aj s čiarovými kódmi."];\n', encoding="utf-8"
        )
        return subprocess.CompletedProcess(["npm"], 0, "", "")

    monkeypatch.setattr(orchestrator, "_run_release_notes_generator", _run)
    return ran


def _committed(root: Path) -> list[str]:
    return sorted(_git(root, "show", "--name-only", "--format=", "HEAD").split())


def test_the_note_and_what_the_app_derives_from_it_land_in_one_commit(
    db_session, project, writes_the_note, monkeypatch
):
    version, _ = _make_version(db_session)
    ran = _generator(monkeypatch)

    orchestrator._commit_release_note(db_session, version.id, project, "1.5.2")

    assert ran == [project / "frontend"]
    assert _committed(project) == ["docs/specs/versions/v1.5.2/RELEASE_NOTES.md", DERIVED]
    assert _git(project, "status", "--porcelain") == ""


def test_a_project_without_the_generator_gets_the_note_alone(db_session, project, writes_the_note, monkeypatch):
    (project / "frontend" / "package.json").write_text(
        json.dumps({"scripts": {"build": "vite build"}}), encoding="utf-8"
    )
    _git(project, "commit", "-qam", "no generator")
    version, _ = _make_version(db_session)
    ran = _generator(monkeypatch)

    orchestrator._commit_release_note(db_session, version.id, project, "1.5.2")

    assert ran == []
    assert _committed(project) == ["docs/specs/versions/v1.5.2/RELEASE_NOTES.md"]


def test_the_agents_own_unfinished_work_is_never_committed_along(db_session, project, writes_the_note, monkeypatch):
    (project / "frontend" / "src" / "App.tsx").write_text("// the agent is still writing this\n", encoding="utf-8")
    version, _ = _make_version(db_session)
    _generator(monkeypatch)

    orchestrator._commit_release_note(db_session, version.id, project, "1.5.2")

    assert "frontend/src/App.tsx" not in _committed(project)
    assert "?? frontend/src/App.tsx" in _git(project, "status", "--porcelain")


def test_a_failed_generator_commits_nothing_and_tells_the_manager_why(
    db_session, project, writes_the_note, monkeypatch
):
    version, _ = _make_version(db_session)
    _generator(monkeypatch, fails=True)
    head = _git(project, "rev-parse", "HEAD")

    orchestrator._commit_release_note(db_session, version.id, project, "1.5.2")

    assert _git(project, "rev-parse", "HEAD") == head, "the note went in without what the app derives from it"
    told = [m for m in _msgs(db_session, version.id) if m.kind == "notification" and m.recipient == "manazer"]
    assert len(told) == 1
    assert "Poznámky k vydaniu v1.5.2 sú zapísané, ale nie v gite" in told[-1].content
    assert "Cannot find module 'tsx'" in told[-1].content


def test_the_generator_is_the_projects_own_npm_script(project, monkeypatch):
    calls: list[tuple[list[str], Path]] = []
    real_run = subprocess.run

    def _run(args, *a, **kw):
        if args and args[0] == "npm":
            calls.append((list(args), Path(kw["cwd"])))
            return subprocess.CompletedProcess(args, 0, "", "")
        return real_run(args, *a, **kw)

    monkeypatch.setattr(orchestrator.subprocess, "run", _run)

    assert orchestrator._regenerate_release_note_derivatives(project) == ([], None)
    assert calls == [(["npm", "run", "--silent", "generate-release-notes"], project / "frontend")]


def test_the_note_written_before_a_release_smoke_brings_its_derivative_too(
    db_session, project, writes_the_note, monkeypatch
):
    version, _ = _make_version(db_session)
    ran = _generator(monkeypatch)

    orchestrator._write_release_note_to_disk(db_session, version.id, project)

    assert ran == [project / "frontend"]
    assert "Kinekus" in (project / DERIVED).read_text(encoding="utf-8")
